/**
 * Export and formatting utilities for reports (Markdown, HTML email, Slack/Teams, PDF)
 */

const ExportUtils = {
  /**
   * Generates formatted GitHub/Standard Markdown
   */
  toMarkdown(report) {
    if (!report) return '';
    const isWSR = report.reportType === 'WSR';
    const lines = [];

    lines.push(`# ${isWSR ? 'Weekly Status Report (WSR)' : 'Daily Status Report (DSR)'}: ${report.projectName || 'Project Update'}`);
    lines.push(`**Date/Week:** ${report.reportDate || report.reportingWeek}`);
    lines.push(`**Overall Project Status:** [${report.projectHealth?.status?.toUpperCase() || 'GREEN'}] - ${report.projectHealth?.rationale || 'On Track'}`);
    lines.push(`**AI Health Confidence:** ${report.projectHealth?.confidenceScore || 95}%\n`);

    lines.push(`## Executive Summary`);
    lines.push(`${report.executiveSummary}\n`);

    if (isWSR && report.managementAttentionRequired) {
      lines.push(`> ⚠️ **MANAGEMENT ATTENTION REQUIRED:**\n> ${report.managementAttentionRequired}\n`);
    }

    if (isWSR) {
      lines.push(`## Key Accomplishments`);
      (report.keyAccomplishments || []).forEach(acc => {
        lines.push(`- **${acc.headline}**: ${acc.impact} *(Owner: ${acc.owner} | ${acc.type || 'Confirmed Fact'})*`);
      });
      lines.push('');

      lines.push(`## Tasks in Progress`);
      (report.tasksInProgress || []).forEach(t => {
        lines.push(`- ${t.task} *(Owner: ${t.owner} | Target: ${t.targetDate || 'Next Sprint'})*`);
      });
      lines.push('');

      lines.push(`## Planned Activities for Next Week`);
      (report.plannedActivitiesNextWeek || []).forEach(p => {
        lines.push(`- [ ] ${p.activity} *(Owner: ${p.owner} | Priority: ${p.priority})*`);
      });
      lines.push('');

      if (report.milestonesAchieved?.length || report.milestonesUpcoming?.length) {
        lines.push(`## Milestones`);
        (report.milestonesAchieved || []).forEach(m => lines.push(`- ✅ **Achieved:** ${m.milestone} (${m.dateAchieved})`));
        (report.milestonesUpcoming || []).forEach(m => lines.push(`- 🎯 **Target:** ${m.milestone} (Target: ${m.targetDate})`));
        lines.push('');
      }
    } else {
      lines.push(`## Work Completed Today`);
      (report.workCompletedToday || []).forEach(w => {
        lines.push(`- [x] **${w.task}** *(Owner: ${w.owner}${w.notes ? ` - ${w.notes}` : ''})*`);
      });
      lines.push('');

      lines.push(`## Tasks Currently in Progress`);
      (report.tasksInProgress || []).forEach(t => {
        lines.push(`- [ ] **${t.task}** *(Owner: ${t.owner} | Status: ${t.status})*`);
      });
      lines.push('');

      lines.push(`## Upcoming Activities / Next Steps`);
      (report.upcomingActivities || []).forEach(u => {
        lines.push(`- [ ] ${u.task} *(Owner: ${u.owner} | Target: ${u.targetDate || 'Tomorrow'})*`);
      });
      lines.push('');
    }

    lines.push(`## Blockers & Dependencies`);
    if (report.blockersAndDependencies && report.blockersAndDependencies.length > 0) {
      report.blockersAndDependencies.forEach(b => {
        lines.push(`- 🛑 **${b.description}**`);
        lines.push(`  - **Owner:** ${b.owner} | **Severity:** ${b.severity} | **Impact:** ${b.impact || 'Delivery bottleneck'}`);
      });
    } else {
      lines.push(`- None reported.`);
    }
    lines.push('');

    lines.push(`## Risks and Issues`);
    (report.risksAndIssues || []).forEach(r => {
      lines.push(`- ⚠️ **${r.risk}** *(Severity: ${r.severity || r.impact || 'Medium'})*`);
      if (r.mitigation) lines.push(`  - *Mitigation:* ${r.mitigation}`);
    });
    lines.push('');

    lines.push(`## Key Decisions`);
    (report.keyDecisions || []).forEach(d => {
      lines.push(`- 📌 **${d.decision}** *(Owner/Stakeholder: ${d.owner || d.stakeholder || 'Team'})*`);
    });
    lines.push('');

    lines.push(`## Action Items`);
    (report.actionItems || report.pendingActionItems || []).forEach(a => {
      lines.push(`- [ ] **${a.task || a.action}** *(Owner: ${a.owner} | Priority: ${a.priority || 'Medium'} | Status: ${a.status || 'Pending'})*`);
    });
    lines.push('');

    if (report.additionalComments) {
      lines.push(`## Additional Comments`);
      lines.push(`${report.additionalComments}\n`);
    }

    lines.push(`---\n*Report generated by AI Status Reporting Agent on ${new Date().toLocaleString()}*`);
    return lines.join('\n');
  },

  /**
   * Generates Slack / Microsoft Teams formatted markup
   */
  toSlack(report) {
    if (!report) return '';
    const isWSR = report.reportType === 'WSR';
    const statusEmoji = report.projectHealth?.status === 'Green' ? ':large_green_circle:' : (report.projectHealth?.status === 'Amber' ? ':large_orange_circle:' : ':red_circle:');

    let out = `${statusEmoji} *${isWSR ? 'Weekly Status Report (WSR)' : 'Daily Status Report (DSR)'}: ${report.projectName}*\n`;
    out += `*Timeline:* ${report.reportDate || report.reportingWeek} | *Health:* *${report.projectHealth?.status?.toUpperCase()}*\n\n`;
    out += `*Executive Summary:*\n>${report.executiveSummary}\n\n`;

    if (isWSR && report.managementAttentionRequired) {
      out += `:rotating_light: *MANAGEMENT ATTENTION:*\n>${report.managementAttentionRequired}\n\n`;
    }

    if (isWSR) {
      out += `*Key Accomplishments:*\n`;
      (report.keyAccomplishments || []).forEach(acc => {
        out += `• *${acc.headline}* - ${acc.impact} (${acc.owner})\n`;
      });
    } else {
      out += `*Completed Today:*\n`;
      (report.workCompletedToday || []).forEach(w => {
        out += `• ${w.task} (${w.owner})\n`;
      });
    }

    out += `\n*Blockers & Dependencies:*\n`;
    if (report.blockersAndDependencies && report.blockersAndDependencies.length > 0) {
      report.blockersAndDependencies.forEach(b => {
        out += `• :warning: *${b.description}* (Owner: ${b.owner} | Severity: ${b.severity})\n`;
      });
    } else {
      out += `• None reported :white_check_mark:\n`;
    }

    out += `\n*Top Action Items:*\n`;
    (report.actionItems || report.pendingActionItems || []).slice(0, 4).forEach(a => {
      out += `• [ ] ${a.task || a.action} (Assigned: *${a.owner}*)\n`;
    });

    return out;
  },

  /**
   * Generates clean HTML email template
   */
  toEmailHtml(report) {
    if (!report) return '';
    const isWSR = report.reportType === 'WSR';
    const health = report.projectHealth?.status || 'Green';
    const healthColor = health === 'Green' ? '#059669' : (health === 'Amber' ? '#d97706' : '#dc2626');
    const healthBg = health === 'Green' ? '#ecfdf5' : (health === 'Amber' ? '#fffbeb' : '#fef2f2');

    return `
    <div style="font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif; max-width: 680px; margin: 0 auto; color: #1f2937; line-height: 1.6;">
      <div style="background: #111827; padding: 24px; border-radius: 8px 8px 0 0; color: #ffffff;">
        <span style="background: #4f46e5; color: #ffffff; padding: 3px 8px; font-size: 11px; font-weight: 700; border-radius: 4px; text-transform: uppercase;">
          ${isWSR ? 'Weekly Status Report' : 'Daily Status Report'}
        </span>
        <h1 style="margin: 12px 0 4px 0; font-size: 22px; color: #ffffff;">${report.projectName}</h1>
        <p style="margin: 0; font-size: 13px; color: #9ca3af;">${report.reportDate || report.reportingWeek}</p>
      </div>

      <div style="border: 1px solid #e5e7eb; border-top: none; padding: 24px; background: #ffffff; border-radius: 0 0 8px 8px;">
        <!-- Status Box -->
        <div style="background: ${healthBg}; border-left: 4px solid ${healthColor}; padding: 14px 18px; margin-bottom: 20px; border-radius: 0 6px 6px 0;">
          <strong style="color: ${healthColor}; font-size: 13px; text-transform: uppercase; letter-spacing: 0.5px;">PROJECT HEALTH: ${health.toUpperCase()}</strong>
          <p style="margin: 4px 0 0 0; font-size: 13px; color: #374151;">${report.projectHealth?.rationale || ''}</p>
        </div>

        <!-- Executive Summary -->
        <h3 style="font-size: 15px; margin: 0 0 8px 0; color: #111827; text-transform: uppercase; letter-spacing: 0.5px;">Executive Summary</h3>
        <p style="margin: 0 0 20px 0; font-size: 14px; color: #4b5563; background: #f9fafb; padding: 14px; border-radius: 6px;">
          ${report.executiveSummary}
        </p>

        ${isWSR && report.managementAttentionRequired ? `
        <div style="background: #fef2f2; border: 1px solid #fecaca; padding: 14px; border-radius: 6px; margin-bottom: 20px;">
          <strong style="color: #dc2626; font-size: 12px; text-transform: uppercase;">Management Attention Required</strong>
          <p style="margin: 4px 0 0 0; font-size: 13px; color: #991b1b;">${report.managementAttentionRequired}</p>
        </div>` : ''}

        <!-- Deliverables -->
        <h3 style="font-size: 15px; margin: 0 0 10px 0; color: #111827; text-transform: uppercase; letter-spacing: 0.5px;">
          ${isWSR ? 'Key Accomplishments' : 'Work Completed Today'}
        </h3>
        <ul style="margin: 0 0 20px 0; padding-left: 20px; font-size: 14px; color: #374151;">
          ${(isWSR ? (report.keyAccomplishments || []) : (report.workCompletedToday || [])).map(item => `
            <li style="margin-bottom: 6px;">
              <strong>${item.headline || item.task}</strong> - <span style="color: #6b7280;">(${item.owner})</span>
            </li>
          `).join('')}
        </ul>

        <!-- Blockers -->
        <h3 style="font-size: 15px; margin: 0 0 10px 0; color: #111827; text-transform: uppercase; letter-spacing: 0.5px;">Blockers & Dependencies</h3>
        ${(report.blockersAndDependencies && report.blockersAndDependencies.length > 0) ? `
          <ul style="margin: 0 0 20px 0; padding-left: 20px; font-size: 14px; color: #dc2626;">
            ${report.blockersAndDependencies.map(b => `
              <li style="margin-bottom: 6px;">
                <strong>${b.description}</strong> - <span style="color: #4b5563;">Owner: ${b.owner} | Severity: ${b.severity}</span>
              </li>
            `).join('')}
          </ul>
        ` : `<p style="font-size: 13px; color: #059669; margin: 0 0 20px 0;">✓ Zero active blockers reported.</p>`}

        <!-- Action Items -->
        <h3 style="font-size: 15px; margin: 0 0 10px 0; color: #111827; text-transform: uppercase; letter-spacing: 0.5px;">Key Action Items</h3>
        <table style="width: 100%; border-collapse: collapse; font-size: 13px; margin-bottom: 20px;">
          <thead>
            <tr style="background: #f3f4f6; text-align: left;">
              <th style="padding: 8px 10px; border: 1px solid #e5e7eb;">Action Item</th>
              <th style="padding: 8px 10px; border: 1px solid #e5e7eb;">Assignee</th>
              <th style="padding: 8px 10px; border: 1px solid #e5e7eb;">Priority</th>
            </tr>
          </thead>
          <tbody>
            ${(report.actionItems || report.pendingActionItems || []).map(a => `
              <tr>
                <td style="padding: 8px 10px; border: 1px solid #e5e7eb;">${a.task || a.action}</td>
                <td style="padding: 8px 10px; border: 1px solid #e5e7eb; color: #4f46e5; font-weight: 600;">${a.owner}</td>
                <td style="padding: 8px 10px; border: 1px solid #e5e7eb;">${a.priority || 'Medium'}</td>
              </tr>
            `).join('')}
          </tbody>
        </table>

        <div style="border-top: 1px solid #e5e7eb; padding-top: 14px; font-size: 11px; color: #9ca3af; text-align: center;">
          Synthesized by AI Status Reporting Agent • Automated Executive Cadence
        </div>
      </div>
    </div>
    `;
  },

  /**
   * Downloads report as a formatted JSON file
   */
  downloadJson(report) {
    if (!report) return;
    const filename = `${report.reportType || 'Report'}_${(report.projectName || 'project').replace(/\s+/g, '_')}_${Date.now()}.json`;
    const dataStr = "data:text/json;charset=utf-8," + encodeURIComponent(JSON.stringify(report, null, 2));
    const dlAnchorElem = document.createElement('a');
    dlAnchorElem.setAttribute("href", dataStr);
    dlAnchorElem.setAttribute("download", filename);
    dlAnchorElem.click();
    dlAnchorElem.remove();
  },

  /**
   * Triggers native print preview for high-resolution PDF export
   */
  printPdf() {
    window.print();
  }
};
